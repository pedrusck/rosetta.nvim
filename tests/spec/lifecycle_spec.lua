local api = require("rosetta")

test("start, stop, variant changes and restored registrations preserve identity contracts", function()
	assert(api.configure({ languages = { "en", "de" } }))
	assert(api.start())
	drain()
	local status = api.status()
	local buf = status.languages[1].buffer
	local ref = assert(api.registration(buf))
	vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "unsaved document" })
	assert(api.stop())
	assert(api.reassign(ref, "en-GB"))
	eq({ "unsaved document" }, vim.api.nvim_buf_get_lines(buf, 0, -1, false))
	assert(api.layout())
	eq(ref, api.registration(buf))
	vim.api.nvim_buf_delete(buf, { force = true })
	drain()
	local result, err = api.reassign(ref, "en-US")
	assert(not result and err.code == "registration")
	assert(api.layout())
	local replacement = api.status().languages[1].buffer
	assert(replacement ~= buf)
	eq({ "" }, vim.api.nvim_buf_get_lines(replacement, 0, -1, false))
end)

test("invalid configuration preserves active registrations", function()
	local before = api.status()
	local result = api.configure({ languages = { "en" } })
	assert(not result)
	eq(before, api.status())
end)
