local helpers = dofile("tests/helpers.lua")

test("preparation settles once and selection invalidates stale picker tokens", function()
	local f = helpers.provider()
	f.ready()
	drain()
	eq(1, #f.events)
	assert(f.events[1].ready)
	local entries, choose = f.provider.model_choices()
	eq({ "first", "second" }, entries)
	local captured = f.provider.capture()
	assert(choose("second"))
	assert(captured.is_current())
	eq("first", captured.prepare({ { role = "user", content = "hello" } }, "hello").model)
	local ok, err = pcall(choose, "first")
	assert(not ok and type(err) == "table" and err.code == "stale_picker")
	f.requests[#f.requests].reply(helpers.response("second ready"))
	eq("second", f.provider.status().model)
	assert(f.provider.status().ready)
end)

test("stop cancels preparation and late credentials cannot resurrect context", function()
	local f = helpers.provider()
	f.provider.activate({
		on_complete = function(result)
			f.events[#f.events + 1] = result
		end,
	})
	f.provider.stop()
	f.credentials[1].reply("late-key")
	drain()
	eq(0, #f.requests)
	eq(1, #f.events)
	assert(f.events[1].cancelled and f.credentials[1].cancelled)
	assert(not f.provider.status().ready)
end)

test("discovery failure preserves readiness and generation errors require recovery", function()
	local f = helpers.provider()
	f.activate()
	f.requests[1].reply({ status = 500, body = "" })
	f.requests[2].reply(helpers.response("ready"))
	assert(f.provider.status().ready)
	local captured = f.provider.capture()
	local results = {}
	captured.dispatch({}, function(response)
		results[#results + 1] = response.status
	end)
	captured.dispatch({}, function(response)
		results[#results + 1] = response.status
	end)
	f.requests[3].reply({ status = 429, body = "" })
	assert(not f.provider.status().ready and f.provider.status().recovery)
	assert(captured.is_current())
	f.requests[4].reply(helpers.response("sibling still valid"))
	eq({ 429, 200 }, results)
	f.provider.stop()
	assert(not captured.is_current())
end)

test("same-endpoint selection survives activation and old probes cannot win", function()
	local f = helpers.provider()
	f.ready()
	local _, choose = f.provider.model_choices()
	choose("second")
	local old_probe = f.requests[#f.requests]
	f.activate()
	old_probe.reply(helpers.response("obsolete"))
	eq("second", f.provider.status().model)
	assert(not f.provider.status().ready)
	f.requests[#f.requests].reply(helpers.response("new context"))
	assert(f.provider.status().ready)
	f.config.provider.base_url = "https://other.invalid/v1"
	f.activate()
	eq("first", f.provider.status().model)
end)
